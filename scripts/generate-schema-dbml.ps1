# Regenerates docs/schema.dbml from the migrations.
# Starts a throwaway PostgreSQL, applies the migrations with the migrate task, and
# reads the schema back with the DBML CLI. Needs Docker and Node.js.
# Runs in Windows PowerShell 5.1 and PowerShell 7. CI fails if the result differs
# from the committed file.

$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$image = 'pgvector/pgvector:0.8.1-pg17'   # Keep in step with compose.yaml and PostgresFixture.
$port = 55432
$name = "schema-dbml-$PID"

# Start a throwaway PostgreSQL container.
Write-Host "==> Starting temporary PostgreSQL container..." -ForegroundColor Cyan
docker run --rm -d --name $name -p "${port}:5432" -e POSTGRES_PASSWORD=postgres -e POSTGRES_DB=schema $image | Out-Null

try {
    # Wait for PostgreSQL to be ready.
    Write-Host "==> Waiting for PostgreSQL to be ready..." -ForegroundColor Cyan
    $ready = $false
    for ($i = 0; $i -lt 30; $i++) {
        docker exec $name pg_isready -U postgres -d schema | Out-Null
        if ($LASTEXITCODE -eq 0) { 
            $ready = $true; break 
        }
        Start-Sleep -Seconds 1
    }
    if (-not $ready) { 
        throw 'PostgreSQL did not start.' 
    }

    # Apply migrations to the throwaway database.
    Write-Host "==> Applying migrations..." -ForegroundColor Cyan
    $env:ConnectionStrings__Database = "Host=localhost;Port=$port;Database=schema;Username=postgres;Password=postgres"
    
    # Run the migrate task to apply migrations.
    dotnet run --project "$root/src/App" \
    --no-launch-profile \
    -- migrate

    if ($LASTEXITCODE -ne 0) { 
        throw 'Migrations failed.' 
    }

    # Generate DBML from the database.
    Write-Host "==> Generating DBML schema..." -ForegroundColor Cyan
    npx --yes -p @dbml/cli@10.3.1 db2dbml postgres "postgresql://postgres:postgres@localhost:$port/schema" -o "$root/docs/schema.dbml"
    if ($LASTEXITCODE -ne 0) { 
        throw 'db2dbml failed.' 
    }

    $file = "$root/docs/schema.dbml"

    # Add a header to the generated file.
    $header = @(
        '// Generated by scripts/generate-schema-dbml.ps1 from the migrations. Do not edit.',
        '// DBML cannot show partial index conditions, expression indexes or triggers.',
        '// For those, see src/App/Data/Configurations and src/App/Data/Migrations.',
        ''
    ) -join "`n"
    [IO.File]::WriteAllText($file, $header + "`n" + [IO.File]::ReadAllText($file))

    Write-Host "✓ Schema generated: docs/schema.dbml" -ForegroundColor Green
}
finally {
    # Clean up the throwaway PostgreSQL container and environment variable.
    Remove-Item Env:ConnectionStrings__Database -ErrorAction SilentlyContinue
    docker stop $name | Out-Null
}
